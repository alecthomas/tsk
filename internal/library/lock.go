package library

import (
	"bytes"
	"os"
	"slices"
	"strings"

	"github.com/alecthomas/errors"
	. "github.com/alecthomas/types/optional"
	"github.com/pelletier/go-toml/v2"
)

// LockFileName is the lock file's name, beside the config file.
const LockFileName = "lock.toml"

const lockHeader = "# Generated by tsk get. Do not edit.\n\n"

// Lock records the commit each import's version resolved to.
type Lock struct {
	Imports []Locked `toml:"import"`
}

// Locked is one library pinned to a commit.
type Locked struct {
	Repository string `toml:"repository"`
	Version    string `toml:"version"`
	Dir        string `toml:"dir,omitempty"`
	// Commit is a full commit hash.
	Commit string `toml:"commit"`
}

// Import returns the import the library was locked for.
func (l Locked) Import() Import {
	return Import{Repository: l.Repository, Version: Some(l.Version), Dir: l.Dir}
}

// Path returns the library's import path, as Import.Path does.
func (l Locked) Path() string {
	return joinPath(l.Repository, l.Dir)
}

// String describes the library's import and commit.
func (l Locked) String() string {
	return l.Import().String() + " (" + l.Short() + ")"
}

// Short returns the commit abbreviated as tsk shows it.
func (l Locked) Short() string {
	return l.Commit[:min(len(l.Commit), 12)]
}

// LoadLock reads a lock file. A missing file locks nothing.
func LoadLock(path string) (Lock, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return Lock{}, nil
	}
	if err != nil {
		return Lock{}, errors.Wrap(err, "read lock file")
	}
	var lock Lock
	if err := toml.NewDecoder(bytes.NewReader(data)).DisallowUnknownFields().Decode(&lock); err != nil {
		return Lock{}, errors.Wrapf(err, "parse %s", path)
	}
	for _, locked := range lock.Imports {
		// Every field is passed to git or names a cache directory.
		if err := locked.check(); err != nil {
			return Lock{}, errors.Wrapf(err, "%s", path)
		}
	}
	return lock, nil
}

// Save writes the lock file.
func (l Lock) Save(path string) error {
	data, err := toml.Marshal(l)
	if err != nil {
		return errors.Wrap(err, "encode lock file")
	}
	return errors.Wrap(os.WriteFile(path, append([]byte(lockHeader), data...), 0o600), "write lock file")
}

// Find returns the entry locking the library with an import path.
func (l Lock) Find(path string) (Locked, bool) {
	i := slices.IndexFunc(l.Imports, func(locked Locked) bool { return locked.Path() == path })
	if i < 0 {
		return Locked{}, false
	}
	return l.Imports[i], true
}

// Check reports whether the lock pins exactly imports, as written.
func (l Lock) Check(imports []Import) error {
	for _, imported := range imports {
		locked, ok := l.Find(imported.Path())
		switch {
		case !ok:
			return errors.Errorf("%s is not locked", imported)
		case locked.Import() != imported:
			return errors.Errorf("%s is locked as %s", imported, locked.Import())
		}
	}
	for _, locked := range l.Imports {
		if !slices.ContainsFunc(imports, func(imported Import) bool { return imported.Path() == locked.Path() }) {
			return errors.Errorf("%s is locked but not imported", locked.Import())
		}
	}
	return nil
}

func (l Locked) check() error {
	if err := checkRepository(l.Repository); err != nil {
		return err
	}
	if l.Dir != "" {
		if err := checkDir(l.Dir); err != nil {
			return errors.Wrapf(err, "%s", l.Repository)
		}
	}
	if err := checkVersion(l.Version); err != nil {
		return errors.Wrapf(err, "%s", l.Repository)
	}
	if !isCommit(l.Commit) {
		return errors.Errorf("%s has invalid commit %q", l.Repository, l.Commit)
	}
	return nil
}

// isCommit accepts full SHA-1 and SHA-256 commit hashes.
func isCommit(commit string) bool {
	if len(commit) != 40 && len(commit) != 64 {
		return false
	}
	return strings.Trim(commit, "0123456789abcdef") == ""
}
