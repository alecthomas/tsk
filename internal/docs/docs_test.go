func shape() ts.ObjectShape {
	rule := ts.ObjectShape{Properties: []ts.Property{
		{Name: "writer", Doc: "Who writes.", Shape: ts.StringShape{}},
		{Name: "maxCount", Shape: ts.NumberShape{}},
	}}
	return ts.ObjectShape{Properties: []ts.Property{
		{Name: "allowReads", Doc: "Rules allowing reads.\nOne per line.", Shape: ts.ArrayShape{Element: rule}},
		{Name: "allowWrites", Doc: "Rules allowing writes.", Shape: ts.ArrayShape{Element: rule}},
		{Name: "mode", Optional: true, Shape: ts.EnumShape{Values: []string{"loose", "strict"}}},
		{Name: "limit", Shape: ts.NumberShape{}},
		{Name: "labels", Shape: ts.RecordShape{Element: ts.StringShape{}}},
	}}
}

func defaults() map[string]any {
	return map[string]any{
		"allowReads": []any{
			map[string]any{"writer": "all", "maxCount": 2.0},
			map[string]any{"writer": "some", "maxCount": 1.0},
		},
		"allowWrites": []any{},
		"limit":       3.0,
		"labels":      map[string]any{"camelKey": "kept"},
	}
}

func analyzers() []docs.Analyzer {
	return []docs.Analyzer{
		{Name: "rules", Doc: "check rules\n\nRules apply to every package.", URL: "https://example.com", Source: "github.com/acme/linters@0123456789ab", Enabled: true,
			Config: Some(docs.Config{Shape: shape(), Defaults: defaults()})},
		{Name: "plain", Doc: "no options", Source: ".tsk/plain.ts", Group: "acme"},
	}
}

func TestTOML(t *testing.T) {
	header := []string{
		`# Generated by tsk config. Options are set to their defaults. Fill in`,
		`# or delete the placeholder entries in empty arrays of tables.`,
	}
	settings := []string{
		``,
		`# Linter libraries whose analyzers run, as repository[@version][//dir]. tsk get adds them and pins their versions in lock.toml; a version given here stays fixed.`,
		`imports = []`,
		``,
		`# Imports, as repository[//dir], to load from local directories instead, relative to this file. They are not fetched or locked.`,
		`replace = {}`,
		``,
		`# Analyzers and groups that do not run. Naming an analyzer wins over naming its group.`,
		`disable = []`,
		``,
		`# Turn every analyzer off except those enable names.`,
		`disable-all = false`,
		``,
		`# Turn every analyzer on except those disable names and those off by default.`,
		`enable-all = false`,
		``,
		`# Analyzers and groups that run. An analyzer off by default runs only if named itself, not by its group. Naming an analyzer wins over naming its group.`,
		`enable = []`,
		``,
		`# Report findings in generated files, which are skipped by default.`,
		`lint-generated = false`,
		``,
		`# Report no findings in _test.go files, as --no-test does.`,
		`no-tests = false`,
		``,
		`# Analyzers that report no findings in _test.go files.`,
		`skip-tests = []`,
		``,
		`# Findings to drop, as golangci-lint's exclusion rules: each sets linters and Go regular expressions for path, path-except, text, and source, which must all match. Paths are relative to the directory containing .tsk.`,
		`exclude = []`,
		``,
		`# Go regular expressions for file paths, relative to the directory containing .tsk, whose findings are all dropped.`,
		`exclude-paths = []`,
	}
	tables := []string{
		``,
		`# rules (enabled, github.com/acme/linters@0123456789ab)`,
		`#`,
		`# check rules`,
		`#`,
		`# Rules apply to every package.`,
		`# https://example.com`,
		`[rules]`,
		`# Rules allowing reads.`,
		`# One per line.`,
		`allow-reads = [{`,
		`  # Who writes.`,
		`  writer = 'all',`,
		`  max-count = 2`,
		`}, {`,
		`  # Who writes.`,
		`  writer = 'some',`,
		`  max-count = 1`,
		`}]`,
		``,
		`# Rules allowing writes.`,
		`allow-writes = [{`,
		`  # Who writes.`,
		`  writer = '',`,
		`  max-count = 0`,
		`}]`,
		``,
		`# mode = <one of "loose", "strict">`,
		``,
		`limit = 3`,
		``,
		`labels = {camelKey = 'kept'}`,
		``,
		`# plain (disabled, group acme, .tsk/plain.ts)`,
		`#`,
		`# no options`,
		`#`,
		`# No config.`,
		``,
	}
	tests := []struct {
		name     string
		settings bool
		expected []string
	}{
		{name: "WithSettings", settings: true, expected: slices.Concat(header, settings, tables)},
		{name: "WithoutSettings", settings: false, expected: slices.Concat(header, tables)},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			var out bytes.Buffer
			assert.NoError(t, docs.TOML(&out, analyzers(), docs.Options{Settings: test.settings}))
			assert.Equal(t, strings.Join(test.expected, "\n"), out.String())
		})
	}
}

func TestList(t *testing.T) {
	var out bytes.Buffer
	assert.NoError(t, docs.List(&out, analyzers()))
	assert.Equal(t, strings.Join([]string{
		`rules  enabled   -     github.com/acme/linters@0123456789ab  check rules`,
		`plain  disabled  acme  .tsk/plain.ts                         no options`,
		``,
	}, "\n"), out.String())
}

